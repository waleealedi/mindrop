import rateLimit from 'express-rate-limit';

// ---------------------------------------------------------------------------
// سقف رفع لكل مستخدم.
//
// **ليش أصلًا:** الدخول مجهول (Anonymous Auth) ومفتاح العميل عام بحكم أنه
// يُشحن داخل الـAPK. يعني أي أحد يقدر يطلب توكن **صحيح تمامًا** لهذا
// المشروع — التوكن يثبت «هذا حساب بمشروعنا»، ما يثبت «هذا صاحب التطبيق».
// وكل رفع مقبول يكلّف نداء Whisper + نداء LLM على حساب المالك. بلا سقف،
// التكلفة مفتوحة.
//
// **ليش المفتاح uid لا IP:** الـIP يتغيّر مع كل شبكة ويتشارك خلف NAT —
// يعاقب أبرياء ويترك المسيء يلتف بتبديل الشبكة. الـuid يجي من توكن موقّع
// تحقّقنا منه فعلًا (`verifyToken`)، فهو المعرّف الوحيد اللي نثق فيه هنا.
// ولهذا لازم يجي هذا الميدلوير **بعد** `verifyToken` بالسلسلة.
//
// **ليش ١٠ بالساعة:** التسجيل هنا «فكرة منطوقة» لا رسالة دردشة. الاستعمال
// الحقيقي بجهاز الاختبار كان ٤–٥ تسجيلات خلال أسابيع، فعشرة بالساعة أوسع
// من أي استخدام بشري متصوَّر (بما فيه جلسة تفريغ أفكار مكثّفة) وتظل تقصّ
// أي إساءة آلية عند حد يُحتمل دفعه. رقم بداية معقول لا قيمة مدروسة —
// عدّله بالأعلى لو ضاق على استعمال حقيقي.
//
// ⚠️ **المخزن بالذاكرة، فهو حارس تكلفة لا حدّ أمني صارم.** خدمة Render
// المجانية تنام وتُعاد تشغيلها، وكل إعادة تشغيل تصفّر العدّادات. لسقف
// حقيقي لا يُصفَّر، يلزم مخزن مشترك (Redis) وهذا يعني اعتمادًا مدفوعًا
// جديدًا — قرار مالك المشروع، مو أثرًا جانبيًا لهذي الجولة.
// ---------------------------------------------------------------------------

/// عشرة رفعات لكل مستخدم بالساعة.
export const UPLOAD_LIMIT_PER_HOUR = 10;
export const UPLOAD_WINDOW_MS = 60 * 60 * 1000;

export const uploadRateLimit = rateLimit({
  windowMs: UPLOAD_WINDOW_MS,
  limit: UPLOAD_LIMIT_PER_HOUR,

  // المفتاح هوية موثّقة، لا عنوان شبكة.
  keyGenerator: (req) => req.uid,

  // ترويسات `RateLimit-*` القياسية، وبلا `X-RateLimit-*` القديمة.
  standardHeaders: 'draft-7',
  legacyHeaders: false,

  // نعطّل فحص الـIP: الحزمة تحذّر من مولّد مفاتيح مخصص لأنها تفترض أنه
  // مبني على IP (ومنها مشاكل IPv6). مفتاحنا uid، فالفحص لا ينطبق.
  validate: { keyGeneratorIpFallback: false },

  handler: (req, res) => {
    console.warn(`[${req.uid}] تجاوز سقف الرفع (${UPLOAD_LIMIT_PER_HOUR}/ساعة)`);
    res.status(429).json({
      error: 'تجاوزت حد الرفع المسموح. حاول بعد شوي.',
      limitPerHour: UPLOAD_LIMIT_PER_HOUR,
    });
  },
});
